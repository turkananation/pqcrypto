import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:pqcrypto/src/common/sha2.dart';

/// Records SHA-256 of the checked-in normalized JSON and writes the Dart
/// constants used by the portable FIPS 202 corpus runner.
///
/// Run from the package root:
/// `dart run tool/fips202/generate_corpus_library.dart`
void main() {
  if (!File('pubspec.yaml').existsSync()) {
    throw StateError('Run from the pqcrypto package root.');
  }

  final fips202Hashes = _pinManifest(
    'test/data/FIPS202/manifest.json',
    const <String>[
      'all_examples.json',
      'shake_truncation.json',
      'byte_aligned_vectors.json',
    ],
  );
  _pinManifest('test/data/SP800185/manifest.json', const <String>[
    'examples.json',
  ]);
  _writeCorpusLibrary(
    allExamples: _readText('test/data/FIPS202/all_examples.json'),
    allExamplesSha256: fips202Hashes['all_examples.json']!,
    truncation: _readText('test/data/FIPS202/shake_truncation.json'),
    truncationSha256: fips202Hashes['shake_truncation.json']!,
  );
}

Map<String, String> _pinManifest(String manifestPath, List<String> jsonNames) {
  final manifestFile = File(manifestPath);
  final original = manifestFile.readAsStringSync();
  final before = jsonDecode(original) as Map<String, dynamic>;
  final directory = manifestFile.parent.path;
  final hashes = <String, String>{
    for (final name in jsonNames)
      name: _sha256Hex(File('$directory/$name').readAsBytesSync()),
  };
  final updated = _upsertNormalized(original, hashes);
  manifestFile.writeAsStringSync(updated);
  final after = jsonDecode(updated) as Map<String, dynamic>;
  _requirePdfRecordsUnchanged(before, after, manifestPath);
  return hashes;
}

String _upsertNormalized(String text, Map<String, String> hashes) {
  final block = StringBuffer('  "normalizedNote": ')
    ..writeln('"SHA-256 of the normalized JSON file bytes.",');
  block.writeln('  "normalized": [');
  final names = hashes.keys.toList();
  for (var i = 0; i < names.length; i++) {
    final name = names[i];
    block
      ..writeln('    {')
      ..writeln('      "file": "$name",')
      ..writeln('      "sha256": "${hashes[name]}"')
      ..write('    }');
    if (i + 1 != names.length) {
      block.writeln(',');
    } else {
      block.writeln();
    }
  }
  block.write('  ]');
  final normalized = block.toString();

  const marker = '\n  "normalizedNote":';
  final index = text.indexOf(marker);
  if (index >= 0) {
    if (text[index - 1] != ',') {
      throw StateError('normalized section is not preceded by a comma');
    }
    return '${text.substring(0, index)}\n$normalized\n}\n';
  }
  if (!text.endsWith('}\n')) {
    throw StateError('manifest does not end with a closing brace');
  }
  final head = text.substring(0, text.length - 2);
  if (!head.endsWith(']\n')) {
    throw StateError('manifest body does not end with the files array');
  }
  return '${head.substring(0, head.length - 1)},\n$normalized\n}\n';
}

void _requirePdfRecordsUnchanged(
  Map<String, dynamic> before,
  Map<String, dynamic> after,
  String manifestPath,
) {
  if (before['standardPdfSha256'] != after['standardPdfSha256']) {
    throw StateError('$manifestPath changed standardPdfSha256');
  }
  final beforeFiles = before['files']! as List<dynamic>;
  final afterFiles = after['files']! as List<dynamic>;
  if (jsonEncode(beforeFiles) != jsonEncode(afterFiles)) {
    throw StateError('$manifestPath changed a PDF record');
  }
  for (final raw in afterFiles) {
    final record = raw as Map<String, dynamic>;
    final name = record['file']! as String;
    if (!name.endsWith('.pdf')) {
      throw StateError('$manifestPath files entry is not a PDF: $name');
    }
  }
}

void _writeCorpusLibrary({
  required String allExamples,
  required String allExamplesSha256,
  required String truncation,
  required String truncationSha256,
}) {
  for (final entry in <String, String>{
    'all_examples.json': allExamples,
    'shake_truncation.json': truncation,
  }.entries) {
    if (entry.value.contains("'''")) {
      throw StateError('${entry.key} contains a raw-string terminator');
    }
  }
  final library = StringBuffer()
    ..writeln('// Generated by tool/fips202/generate_corpus_library.dart.')
    ..writeln('// Do not edit by hand.')
    ..writeln('//')
    ..writeln('// Each string is the checked-in JSON file text, including its')
    ..writeln('// trailing newline. The SHA-256 constants are the digests of')
    ..writeln('// those file bytes and match test/data/FIPS202/manifest.json.')
    ..writeln()
    ..writeln("const String fips202AllExamplesSha256 = '$allExamplesSha256';")
    ..writeln()
    ..writeln("const String fips202AllExamplesJson = r'''$allExamples''';")
    ..writeln()
    ..writeln(
      "const String fips202ShakeTruncationSha256 = '$truncationSha256';",
    )
    ..writeln()
    ..writeln("const String fips202ShakeTruncationJson = r'''$truncation''';");
  File('test/fips202_corpus.dart').writeAsStringSync(library.toString());
}

String _readText(String path) {
  final bytes = File(path).readAsBytesSync();
  final text = utf8.decode(bytes);
  if (!_identicalBytes(bytes, utf8.encode(text))) {
    throw StateError('$path is not stable UTF-8');
  }
  return text;
}

bool _identicalBytes(Uint8List left, Uint8List right) {
  if (left.length != right.length) return false;
  for (var i = 0; i < left.length; i++) {
    if (left[i] != right[i]) return false;
  }
  return true;
}

String _sha256Hex(Uint8List bytes) {
  final digest = sha256(bytes);
  final hex = StringBuffer();
  for (final byte in digest) {
    hex.write(byte.toRadixString(16).padLeft(2, '0'));
  }
  return hex.toString();
}
